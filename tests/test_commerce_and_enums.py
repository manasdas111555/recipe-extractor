class TestLanguageCodesFlexibility:
    """Verifies that preferred_language accepts arbitrary clean language strings."""

    def test_arbitrary_language_codes_accepted(self):
        """Arbitrary valid language strings from UI and bots are accepted without enum restrictions."""
        test_languages = [
            "en",
            "hi",
            "es",
            "fr",
            "de",
            "ja",
            "zh-CN",
            "pt-BR",
            "te",
            "ta",
            "bn",
            "mr",
            "gu",
            "kn",
            "ml",
            "pa",
        ]
        for lang in test_languages:
            req = ExtractRequest(video_url="https://www.instagram.com/reel/123456789/", preferred_language=lang)
            assert req.preferred_language == lang

    def test_language_code_normalization(self):
        """Whitespace is safely stripped and empty/None defaults to 'en'."""
        req1 = ExtractRequest(video_url="https://www.instagram.com/reel/123456789/", preferred_language="  hi  ")
        assert req1.preferred_language == "hi"

        req2 = ExtractRequest(video_url="https://www.instagram.com/reel/123456789/", preferred_language=None)
        assert req2.preferred_language == "en"

        req3 = ExtractRequest(video_url="https://www.instagram.com/reel/123456789/", preferred_language="   ")
        assert req3.preferred_language == "en"
