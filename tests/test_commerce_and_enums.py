"""
Tests for UPA-1216: Commerce Link Validation, Admin Key Hygiene & Enum Bounds
=============================================================================
Verifies:
1. Commerce Link Validation:
   - Every URL emitted by AffiliateEngine passes validate_merchant_redirect_url.
   - All real/legitimate merchant hosts (swiggy.com, ajio.com, nykaa.com, earnkaro.com,
     zepto.now, zeptonow.com, google.com, amazon.in, flipkart.com, etc.) are allowed.
   - Unauthorized / external merchant hosts are rejected.
   - zepto.now vs zeptonow.com handling.
   - Outbound affiliate redirect endpoint (/api/v1/affiliate/redirect) rejects bad hosts (400)
     and accepts valid ones (307).

2. Admin Key Hygiene & Rate Limiting:
   - Valid admin key succeeds.
   - Invalid or unset key returns 403.
   - hmac.compare_digest with bytes comparison.
   - Rate limiting via QuotaManager: 5 attempts allowed per 60s per client IP, 6th blocked with 429.
   - Admin key values never leaked in response or logs.

3. domain_hint Single Source of Truth & Enum Bounds:
   - Canonical single source of truth data file (frontend/src/data/domain_options.json) contains
     the exact nine domain IDs.
   - Backend DomainHint enum dynamically derives from the canonical source.
   - Frontend DOMAIN_OPTIONS imports directly from the canonical source without duplication.
   - All frontend sample chip domain IDs match the canonical source.
   - Case-insensitivity normalization.
   - Invalid domain_hint rejected with validation error (422).

4. Language Code Flexibility:
   - Arbitrary valid language codes accepted without restrictive enum.
"""

