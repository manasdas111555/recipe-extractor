class TestAdminKeyHygiene:
    """Verifies admin authentication security, bytes comparison, and rate limiting."""

    def test_valid_admin_key_succeeds(self):
        """Valid admin key authenticates successfully."""
        get_quota_manager().reset_rate_limits_for_testing()
        with patch.object(settings, "ADMIN_API_KEY", "super_secret_admin_key_999"):
            resp = client.get(
                "/api/v1/telemetry/metrics",
                headers={"X-Admin-Api-Key": "super_secret_admin_key_999"}
            )
            assert resp.status_code == 200

    def test_invalid_admin_key_fails_closed(self):
        """Invalid admin key returns 403 Forbidden."""
        get_quota_manager().reset_rate_limits_for_testing()
        with patch.object(settings, "ADMIN_API_KEY", "super_secret_admin_key_999"):
            resp = client.get(
                "/api/v1/telemetry/metrics",
                headers={"X-Admin-Api-Key": "wrong_key"}
            )
            assert resp.status_code == 403
            assert "Invalid Admin API Key" in resp.json()["detail"]

    def test_unset_admin_key_fails_closed(self):
        """Unset ADMIN_API_KEY on server returns 403 Forbidden."""
        get_quota_manager().reset_rate_limits_for_testing()
        with patch.object(settings, "ADMIN_API_KEY", None):
            with patch.dict(os.environ, {"ADMIN_API_KEY": ""}, clear=False):
                resp = client.get(
                    "/api/v1/telemetry/metrics",
                    headers={"X-Admin-Api-Key": "some_attempt"}
                )
                assert resp.status_code == 403

    def test_admin_auth_rate_limiting(self):
        """5 attempts allowed per 60s per client IP; 6th attempt returns 429 Too Many Requests."""
        get_quota_manager().reset_rate_limits_for_testing()
        test_ip = "192.0.2.77"

        with patch.object(settings, "ADMIN_API_KEY", "valid_admin_key"):
            # First 5 attempts (even if failing or succeeding) should not be blocked by 429
            for i in range(5):
                resp = client.get(
                    "/api/v1/telemetry/metrics",
                    headers={"X-Admin-Api-Key": "wrong_key", "X-Forwarded-For": test_ip}
                )
                assert resp.status_code == 403, f"Attempt {i+1} should return 403, got {resp.status_code}"

            # 6th attempt must be blocked with 429
            resp_6 = client.get(
                "/api/v1/telemetry/metrics",
                headers={"X-Admin-Api-Key": "valid_admin_key", "X-Forwarded-For": test_ip}
            )
            assert resp_6.status_code == 429
            assert "Too many admin authentication attempts" in resp_6.json()["detail"]


