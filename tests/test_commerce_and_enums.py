class TestCommerceValidation:
    """Validates merchant URL allowlisting and AffiliateEngine URL generation."""

    def test_all_affiliate_engine_emitted_urls_pass_validation(self):
        """Ensure every URL generated by AffiliateEngine passes validate_merchant_redirect_url."""
        engine = AffiliateEngine()
        test_item = "Turmeric Powder Haldi"

        generated_urls = [
            engine.generate_amazon_url(test_item),
            engine.generate_earnkaro_url("https://www.flipkart.com/search?q=haldi"),
            engine.generate_flipkart_url(test_item),
            engine.generate_meesho_url(test_item),
            engine.generate_myntra_url(test_item),
            engine.generate_ajio_url(test_item),
            engine.generate_nykaa_url(test_item),
            engine.generate_google_shopping_url(test_item),
            engine.generate_blinkit_url(test_item),
            engine.generate_zepto_url(test_item),
            engine.generate_instamart_url(test_item),
            engine.generate_jiomart_url(test_item),
        ]

        for url in generated_urls:
            is_valid, err = validate_merchant_redirect_url(url)
            assert is_valid is True, f"AffiliateEngine URL failed validation: {url} | Error: {err}"

    def test_enrich_product_links_all_urls_pass_validation(self):
        """Ensure all URLs generated by enrich_product_links pass validate_merchant_redirect_url."""
        engine = AffiliateEngine()
        product = {"name": "Organic Ghee", "price": "₹500"}

        # Test recipe category (includes quick commerce + general)
        enriched_recipe = engine.enrich_product_links(product, category="RECIPE")
        for key, url in enriched_recipe.items():
            if key.endswith("_url") and url:
                is_valid, err = validate_merchant_redirect_url(url)
                assert is_valid is True, f"Enriched recipe link '{key}' failed validation: {url} | Error: {err}"

        # Test fashion category (includes fashion stores)
        enriched_fashion = engine.enrich_product_links(product, category="FASHION")
        for key, url in enriched_fashion.items():
            if key.endswith("_url") and url:
                is_valid, err = validate_merchant_redirect_url(url)
                assert is_valid is True, f"Enriched fashion link '{key}' failed validation: {url} | Error: {err}"

    def test_required_merchant_hosts_accepted(self):
        """Verify all backlog-specified real merchant hosts are accepted."""
        required_hosts = [
            "swiggy.com",
            "ajio.com",
            "nykaa.com",
            "earnkaro.com",
            "zepto.now",
            "zeptonow.com",
            "google.com",
            "amazon.in",
            "amazon.com",
            "flipkart.com",
            "meesho.com",
            "myntra.com",
            "blinkit.com",
            "instamart.com",
            "bigbasket.com",
            "jiomart.com",
        ]
        for host in required_hosts:
            test_url = f"https://www.{host}/search?q=test"
            is_valid, err = validate_merchant_redirect_url(test_url)
            assert is_valid is True, f"Required host {host} should be accepted. Error: {err}"

    def test_unauthorized_external_hosts_rejected(self):
        """Ensure unauthorized / external hosts are strictly rejected."""
        unauthorized_urls = [
            "https://evil.com/deal",
            "https://attacker.com/malicious",
            "https://amazon.in.attacker.com/phishing",
            "https://fake-zepto.com/buy",
            "http://swiggy.com/insecure",  # HTTP rejected
            "https://user:pass@amazon.in/s?k=test",  # Credentials rejected
            "https://amazon.in:8080/s?k=test",  # Non-standard port rejected
            "",  # Empty rejected
            "not_a_url",  # Malformed rejected
        ]
        for url in unauthorized_urls:
            is_valid, err = validate_merchant_redirect_url(url)
            assert is_valid is False, f"Unauthorized URL should have been rejected: {url}"

    def test_zepto_domain_variants(self):
        """Verify both zepto.now and zeptonow.com are handled safely."""
        assert is_allowed_domain("zepto.now", ALLOWED_MERCHANT_DOMAINS) is True
        assert is_allowed_domain("app.zepto.now", ALLOWED_MERCHANT_DOMAINS) is True
        assert is_allowed_domain("zeptonow.com", ALLOWED_MERCHANT_DOMAINS) is True
        assert is_allowed_domain("www.zeptonow.com", ALLOWED_MERCHANT_DOMAINS) is True
        # False positives blocked
        assert is_allowed_domain("fakezeptonow.com", ALLOWED_MERCHANT_DOMAINS) is False
        assert is_allowed_domain("zepto.now.attacker.com", ALLOWED_MERCHANT_DOMAINS) is False

    def test_affiliate_redirect_endpoint_integration(self):
        """Test the /api/v1/affiliate/redirect endpoint enforces validate_merchant_redirect_url."""
        # Valid merchant redirect returns 307
        valid_url = "https://www.amazon.in/s?k=mixer+grinder&tag=manasdas11155-21"
        resp = client.get(
            "/api/v1/affiliate/redirect",
            params={"url": valid_url, "merchant": "amazon"},
            follow_redirects=False,
        )
        assert resp.status_code == 307
        assert resp.headers["location"] == valid_url

        # Invalid/unauthorized merchant returns 400
        invalid_url = "https://evil-phishing.com/steal-creds"
        resp_bad = client.get(
            "/api/v1/affiliate/redirect",
            params={"url": invalid_url, "merchant": "evil"},
            follow_redirects=False,
        )
        assert resp_bad.status_code == 400
        assert "Prohibited merchant host" in resp_bad.json()["detail"]


