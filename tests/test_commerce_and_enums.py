class TestDomainHintEnum:
    """Verifies domain_hint bounds, backend-frontend single source of truth, and normalization."""

    EXPECTED_DOMAINS = [
        "auto",
        "recipe",
        "kitchen_product",
        "fitness_workout",
        "interior_design",
        "gaming",
        "tech_diy",
        "unboxing",
        "diy",
    ]

    def test_canonical_json_source_contains_exact_nine_ids(self):
        """The canonical JSON data file contains the exact nine required IDs in order."""
        json_path = Path(__file__).resolve().parent.parent / "frontend" / "src" / "data" / "domain_options.json"
        assert json_path.exists(), f"Canonical JSON file does not exist at {json_path}"

        with open(json_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        assert isinstance(data, list), "Canonical data must be a JSON array"
        assert len(data) == 9, f"Expected 9 items in canonical JSON, got {len(data)}"

        extracted_ids = []
        for item in data:
            assert isinstance(item, dict), "Each option item must be an object"
            assert "id" in item and "label" in item and "icon" in item
            assert len(item["label"].strip()) > 0
            assert len(item["icon"].strip()) > 0
            extracted_ids.append(item["id"])

        assert extracted_ids == self.EXPECTED_DOMAINS

    def test_backend_domain_hint_derived_from_canonical_json(self):
        """Backend DomainHint enum is dynamically derived from the canonical JSON source."""
        assert CANONICAL_DOMAIN_IDS == self.EXPECTED_DOMAINS
        actual_enum_values = [e.value for e in DomainHint]
        assert actual_enum_values == self.EXPECTED_DOMAINS
        assert len(DomainHint) == 9

        # Ensure all enum attributes resolve correctly
        for d in self.EXPECTED_DOMAINS:
            member = getattr(DomainHint, d.upper())
            assert member.value == d
            assert DomainHint(d) == member

    def test_frontend_consumes_domain_options_json_directly(self):
        """Verify frontend/src/app/page.tsx imports DOMAIN_OPTIONS from domain_options.json."""
        frontend_page_path = Path(__file__).resolve().parent.parent / "frontend" / "src" / "app" / "page.tsx"
        assert frontend_page_path.exists()

        with open(frontend_page_path, "r", encoding="utf-8") as f:
            content = f.read()

        # Verify import statement exists
        assert re.search(r"import\s+DOMAIN_OPTIONS\s+from\s+['\"][^'\"]*domain_options\.json['\"];", content), (
            "frontend/src/app/page.tsx must import DOMAIN_OPTIONS from domain_options.json"
        )
        # Verify no second independent hardcoded array definition exists in page.tsx
        assert not re.search(r"const\s+DOMAIN_OPTIONS\s*=\s*\[", content), (
            "frontend/src/app/page.tsx must not maintain an independent hardcoded DOMAIN_OPTIONS array"
        )

    def test_frontend_sample_chips_accepted(self):
        """Verify all domain hints used by sample chips in the frontend are valid DomainHint values."""
        frontend_page_path = Path(__file__).resolve().parent.parent / "frontend" / "src" / "app" / "page.tsx"
        assert frontend_page_path.exists()

        with open(frontend_page_path, "r", encoding="utf-8") as f:
            content = f.read()

        match = re.search(r"const sampleUrls\s*=\s*\[(.*?)\];", content, re.DOTALL)
        assert match is not None, "Could not find sampleUrls in frontend/src/app/page.tsx"
        sample_domains = set(re.findall(r"domain:\s*['\"]([^'\"]+)['\"]", match.group(1)))
        for sd in sample_domains:
            assert sd in set(self.EXPECTED_DOMAINS), f"Sample chip domain '{sd}' not in DomainHint enum"

    def test_extract_request_accepts_all_domain_hints(self):
        """ExtractRequest accepts all valid domain hints."""
        for d in self.EXPECTED_DOMAINS:
            req = ExtractRequest(video_url="https://www.instagram.com/reel/123456789/", domain_hint=d)
            assert req.domain_hint == DomainHint(d)

    def test_extract_request_normalizes_case_and_whitespace(self):
        """ExtractRequest normalizes case and whitespace for domain_hint."""
        req1 = ExtractRequest(video_url="https://www.instagram.com/reel/123456789/", domain_hint=" RECIPE ")
        assert req1.domain_hint == DomainHint.RECIPE

        req2 = ExtractRequest(video_url="https://www.instagram.com/reel/123456789/", domain_hint="Tech_Diy")
        assert req2.domain_hint == DomainHint.TECH_DIY

    def test_extract_request_rejects_invalid_domain_hint(self):
        """ExtractRequest rejects invalid domain hints with validation error."""
        invalid_hints = ["invalid_hint", "food", "sports", "crypto", "123"]
        for bad in invalid_hints:
            with pytest.raises(Exception):
                ExtractRequest(video_url="https://www.instagram.com/reel/123456789/", domain_hint=bad)

    def test_extract_endpoint_validation_behavior(self):
        """API /api/v1/extract endpoint rejects invalid domain_hint with HTTP 422."""
        resp = client.post(
            "/api/v1/extract",
            json={"video_url": "https://www.instagram.com/reel/123456789/", "domain_hint": "unsupported_xyz"}
        )
        assert resp.status_code == 422


